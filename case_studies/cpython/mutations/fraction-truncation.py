#@ ensures result == (c in "0123456789")
def _is_ascii_digit(c: str) -> bool:
    return c in "0123456789"






























































































_FRACTION_CORRECTION = [100000, 10000, 1000, 100, 10]


#@ ensures not raised() ==> len(result) == 4
#@ ensures len(tstr) < 2 ==> raised()
#@ ensures len(tstr) == 3 ==> raised()
#@ ensures (not raised() and len(tstr) == 2) ==> (result[1] == 0 and result[2] == 0 and result[3] == 0)
#@ ensures not raised() ==> (decimal_valid(tstr[:2]) and result[0] == int(tstr[:2]))
#@ ensures len(tstr) == 2 ==> (raised() == (not decimal_valid(tstr[:2])))
#@ ensures (not raised() and tstr[2:3] == ":" and len(tstr) > 2) ==> (decimal_valid(tstr[3:5]) and result[1] == int(tstr[3:5]))
#@ ensures (not raised() and tstr[2:3] == ":" and len(tstr) > 5) ==> (decimal_valid(tstr[6:8]) and result[2] == int(tstr[6:8]))
