#@ ensures (not raised() and tstr[2:3] != ":" and len(tstr) > 6) ==> (tstr[6:7] in ".," and decimal_valid(tstr[7:13]) and all(c in "0123456789" for c in tstr[13:]))
#@ ensures (not raised() and tstr[2:3] != ":" and len(tstr) == 4) ==> result[2] == 0
#@ ensures (not raised() and tstr[2:3] == ":" and len(tstr) == 5) ==> result[2] == 0
#@ ensures raised() == (not (decimal_valid(tstr[:2]) and (len(tstr) == 2 or (tstr[2:3] == ":" and len(tstr) >= 5 and decimal_valid(tstr[3:5]) and (len(tstr) == 5 or (len(tstr) >= 8 and tstr[5:6] == ":" and decimal_valid(tstr[6:8]) and (len(tstr) == 8 or (len(tstr) >= 10 and tstr[8:9] in ".," and decimal_valid(tstr[9:15]) and all(c in "0123456789" for c in tstr[15:])))))) or (tstr[2:3] != ":" and len(tstr) >= 4 and decimal_valid(tstr[2:4]) and (len(tstr) == 4 or (len(tstr) >= 6 and decimal_valid(tstr[4:6]) and (len(tstr) == 6 or (len(tstr) >= 8 and tstr[6:7] in ".," and decimal_valid(tstr[7:13]) and all(c in "0123456789" for c in tstr[13:])))))))))
def _parse_hh_mm_ss_ff(tstr: str) -> list[int]:
    # Parses things of the form HH[:?MM[:?SS[{.,}fff[fff]]]]
    len_str = len(tstr)

    time_comps = [0, 0, 0, 0]
    pos = 0
    for comp in range(0, 3):
        # proof note: len(time_comps) == 4
        # proof note: pos <= len(tstr)
        # proof note: decimal_valid(tstr[:2])
        # proof note: time_comps[0] == int(tstr[:2])
        # proof note: has_sep == (tstr[2:3] == ":")
        # proof note: time_comps[3] == 0
        # proof note: 1 <= comp and comp <= 3
        # proof note: comp == 1 ==> (time_comps[1] == 0 and time_comps[2] == 0)
        # proof note: comp == 2 ==> time_comps[2] == 0
        # proof note: (comp >= 2 and has_sep) ==> (decimal_valid(tstr[3:5]) and time_comps[1] == int(tstr[3:5]))
        # proof note: (comp >= 3 and has_sep) ==> (decimal_valid(tstr[6:8]) and time_comps[2] == int(tstr[6:8]))
        # proof note: (comp >= 2 and not has_sep) ==> (decimal_valid(tstr[2:4]) and time_comps[1] == int(tstr[2:4]))
        # proof note: (comp >= 3 and not has_sep) ==> (decimal_valid(tstr[4:6]) and time_comps[2] == int(tstr[4:6]))
        # proof note: (comp >= 2 and has_sep and len(tstr) > 5) ==> tstr[5:6] == ":"
        # proof note: len(tstr) != 2
        # proof note: len(tstr) == 3 ==> comp == 1
        if (len_str - pos) < 2:
            raise ValueError("Incomplete time component")

        time_comps[comp] = int(tstr[pos:pos+2])

        pos += 2
        next_char = tstr[pos:pos+1]

        if comp == 0:
            has_sep = next_char == ':'

        if not next_char or comp >= 2:
            break

        if has_sep and next_char != ':':
            raise ValueError("Invalid time separator: %c" % next_char)

        pos += has_sep

    if pos < len_str:
        if tstr[pos] not in '.,':
            raise ValueError("Invalid microsecond separator")
        else:
            pos += 1

            len_remainder = len_str - pos

            if len_remainder >= 6:
                to_parse = 5
            else:
                to_parse = len_remainder

            time_comps[3] = int(tstr[pos:(pos+to_parse)])
            if to_parse < 6:
                time_comps[3] *= _FRACTION_CORRECTION[to_parse-1]
            if (len_remainder > to_parse
                    and not all(map(_is_ascii_digit, tstr[(pos+to_parse):]))):
                raise ValueError("Non-digit values in unparsed fraction")

    return time_comps





































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































